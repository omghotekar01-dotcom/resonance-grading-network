const commonSpectrum = (peaks: Scan["spectrum"]["peaks"]): Scan["spectrum"] => ({
  domainHz: [200, 6000],
  noiseFloorDb: -58,
  peaks,
});

function scan(s: Omit<Scan, "spectrum"> & { peaks: Scan["spectrum"]["peaks"] }): Scan {
  const { peaks, ...rest } = s;
  return { ...rest, spectrum: commonSpectrum(peaks) };
}

